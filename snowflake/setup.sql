-- Run once in Snowflake as ACCOUNTADMIN before starting the pipeline.

CREATE WAREHOUSE IF NOT EXISTS PIPELINE_WH
    WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS CUSTOMER_PIPELINE;
CREATE SCHEMA IF NOT EXISTS CUSTOMER_PIPELINE.RAW;
CREATE SCHEMA IF NOT EXISTS CUSTOMER_PIPELINE.ANALYTICS;

CREATE TABLE IF NOT EXISTS CUSTOMER_PIPELINE.RAW.CUSTOMERS_RAW (
    RECORD_METADATA VARIANT,
    RECORD_CONTENT  VARIANT
);

CREATE TABLE IF NOT EXISTS CUSTOMER_PIPELINE.RAW.TRANSACTIONS_RAW (
    RECORD_METADATA VARIANT,
    RECORD_CONTENT  VARIANT
);

CREATE ROLE IF NOT EXISTS PIPELINE_ROLE;
GRANT USAGE ON WAREHOUSE PIPELINE_WH TO ROLE PIPELINE_ROLE;
GRANT USAGE ON DATABASE CUSTOMER_PIPELINE TO ROLE PIPELINE_ROLE;
GRANT ALL ON SCHEMA CUSTOMER_PIPELINE.RAW TO ROLE PIPELINE_ROLE;
GRANT ALL ON ALL TABLES IN SCHEMA CUSTOMER_PIPELINE.RAW TO ROLE PIPELINE_ROLE;
GRANT ALL ON FUTURE TABLES IN SCHEMA CUSTOMER_PIPELINE.RAW TO ROLE PIPELINE_ROLE;
GRANT ALL ON SCHEMA CUSTOMER_PIPELINE.ANALYTICS TO ROLE PIPELINE_ROLE;
GRANT ALL ON FUTURE TABLES IN SCHEMA CUSTOMER_PIPELINE.ANALYTICS TO ROLE PIPELINE_ROLE;

CREATE USER IF NOT EXISTS PIPELINE_SVC_USER DEFAULT_ROLE = PIPELINE_ROLE DEFAULT_WAREHOUSE = PIPELINE_WH;
GRANT ROLE PIPELINE_ROLE TO USER PIPELINE_SVC_USER;

